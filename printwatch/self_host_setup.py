"""Generate private settings for an authenticated Caddy deployment; never publish them."""
import argparse
import json
import os
import re
import secrets
from .config import ROOT

def prepare(hostname, username, password_hash, folder):
    hostname = hostname.lower()
    labels = hostname.split('.')
    if (len(hostname) > 253 or len(labels) < 2 or any(
        not re.fullmatch(r'[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?', part) for part in labels)):
        raise ValueError('Use a DNS hostname only, without https://, port or path.')
    if not re.fullmatch(r'[a-z0-9_-]{1,64}', username):
        raise ValueError('Username: lowercase letters, numbers, underscore or hyphen, maximum 64 characters.')
    if not re.fullmatch(r'\$2[aby]\$\d{2}\$[./A-Za-z0-9]{53}', password_hash):
        raise ValueError('Supply a bcrypt hash generated by caddy hash-password, never a plaintext password.')
    folder.mkdir(parents=True, exist_ok=True)
    settings = folder/'mobile-access.json'
    caddy = folder/'Caddyfile'
    if settings.exists() or caddy.exists():
        raise FileExistsError('Existing remote settings or Caddyfile preserved. Review or back them up before switching modes.')
    token = secrets.token_urlsafe(48)
    blocks = []
    for suffix, port in (('', 7127), (':8443', 7128)):
        blocks.append(f'''{hostname}{suffix} {{
    basic_auth {{
        {username} {password_hash}
    }}
    reverse_proxy 127.0.0.1:{port} {{
        header_up -Authorization
        header_up -Tailscale-*
        header_up X-PrintWatch-Proxy-Token {token}
    }}
}}
''')
    for path, content in ((settings, json.dumps({'hostname':hostname,'proxy_token':token},indent=2)+'\n'),
                          (caddy, '\n'.join(blocks))):
        fd = os.open(path, os.O_WRONLY|os.O_CREAT|os.O_EXCL, 0o600)
        with os.fdopen(fd, 'w') as file:
            file.write(content)
    return hostname

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--hostname', required=True)
    parser.add_argument('--user', required=True)
    parser.add_argument('--password-hash', required=True)
    args = parser.parse_args()
    try:
        hostname = prepare(args.hostname, args.user, args.password_hash, ROOT/'data')
    except (ValueError, FileExistsError) as error:
        parser.error(str(error))
    print('Private files generated in data/. Do not commit or share them.')
    print('Install data/Caddyfile on the same machine, validate it, then restart PrintWatch.')
    print('AI dashboard: https://'+hostname+'/')
    print('Printer controls: https://'+hostname+':8443/')
    print('Nothing has been published and no firewall, DNS or running service has been changed.')

if __name__ == '__main__':
    main()
